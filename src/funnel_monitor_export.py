"""Business monitoring layout; reads the same frozen, filtered five-stage facts.

Only presentation and explicitly labelled quantity summaries live here. No model,
catalog reads, lifecycle writes, or additional date-range queries are performed.
The workbook is generated by the application's existing streaming Excel stack.
"""
from collections import OrderedDict
from datetime import date, timedelta
from decimal import Decimal

from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

import order_analytics as service
from runtime_support import checkpoint

FORMAT_VERSION = 'monitor-1'
SCOPES = ('大盘', '山东仓', '河北仓')
NUMBER = '#,##0.##########;[Red]-#,##0.##########;0'
INTEGER = '#,##0;[Red]-#,##0;0'
MONEY = '#,##0.00;[Red]-#,##0.00;0.00'
PERCENT = '0.00%;[Red]-0.00%;0.00%'
PALETTE = {
    'title': ('142B40', 'FFFFFF', 17, True),
    'header': ('24536B', 'FFFFFF', 11, True),
    'section': ('17324D', 'FFFFFF', 11, True),
    'note': ('F1F6FA', '66788B', 10, False),
    'odd': ('FFFFFF', '142B40', 11, False),
    'even': ('EBF3F8', '142B40', 11, False),
}
STYLES = {key: (PatternFill('solid', fgColor=fill),
                Font(name='微软雅黑', size=size, bold=bold, color=fg))
          for key, (fill, fg, size, bold) in PALETTE.items()}
ALIGN = Alignment(vertical='center', wrap_text=True, indent=1)


def units(rows):
    return list(dict.fromkeys(str(r['unit']) for r in rows
                             if r['scope'] == '纳入' and r.get('unit') not in (None, '')))


def quantity(rows, stage, unit):
    values = [r['quantities'][stage] for r in rows if r['scope'] == '纳入'
              and str(r.get('unit')) == unit and r['valid'][stage]]
    return sum(values, Decimal(0)) if values else None


def quantity_ratio(rows, before, after, unit):
    cohort = [r for r in rows if r['scope'] == '纳入' and str(r.get('unit')) == unit
              and r['valid'][before] and r['valid'][after]]
    x = sum((r['quantities'][before] for r in cohort), Decimal(0))
    y = sum((r['quantities'][after] for r in cohort), Decimal(0))
    return y / x if cohort and x > 0 else None


def known_value(metrics, stage):
    """No known prices is unknown, not a zero-cost stage."""
    v = metrics['stages'][stage]
    return v['value'] if v['valid_rows'] > v['unpriced'] else None


def receipt_coverage(rows):
    eligible = [r for r in rows if r['scope'] == '纳入']
    orders = list(dict.fromkeys(r['order'] for r in eligible))
    complete = sum(all(r['valid']['receipt'] for r in eligible if r['order'] == oid)
                   for oid in orders)
    return complete, complete / len(orders) if orders else None


class Sheet:
    def __init__(self, book, name, widths, cancel=None):
        self.ws = book.create_sheet(name)
        self.ws.sheet_view.showGridLines = False
        self.ws.freeze_panes = 'B5'
        self.ws.sheet_properties.pageSetUpPr.fitToPage = True
        self.ws.page_setup.orientation = 'landscape'
        self.ws.page_setup.paperSize = '9'  # OOXML A4; also supported by write-only sheets.
        self.ws.page_setup.fitToWidth = 1
        self.ws.page_setup.fitToHeight = 0
        self.ws.print_title_rows = '1:4'
        self.count = 0
        self.width = len(widths)
        self.cancel = cancel
        for col, width in enumerate(widths, 1):
            self.ws.column_dimensions[get_column_letter(col)].width = width

    def row(self, values, kind=None, fmt=NUMBER, height=28, merge=False, formats=None, comments=None):
        checkpoint(self.cancel)
        self.count += 1
        self.ws.row_dimensions[self.count].height = height
        style = kind or ('even' if self.count % 2 == 0 else 'odd')
        fill, font = STYLES[style]
        cells = []
        for index, value in enumerate(list(values) + [None] * (self.width - len(values))):
            value = float(value) if isinstance(value, Decimal) else value
            c = WriteOnlyCell(self.ws, value)
            if isinstance(value, str):
                c.data_type = 's'  # IDs and user-supplied formula-looking names stay text.
            c.fill, c.font, c.alignment = fill, font, ALIGN
            if comments and index in comments:
                from openpyxl.comments import Comment
                c.comment=Comment(comments[index],'补货助手')
            if isinstance(value, (int, float)):
                c.number_format = (formats or {}).get(index, fmt)
                if c.number_format == NUMBER and float(value).is_integer():
                    c.number_format = INTEGER
            cells.append(c)
        if merge:
            self.ws.merged_cells.add(f'A{self.count}:{get_column_letter(self.width)}{self.count}')
        self.ws.append(cells)

    def band(self, text):
        self.row([text], 'section', merge=True)

    def note(self, text):
        self.row([text], 'note', height=38, merge=True)


def period_windows(as_of):
    today = date.fromisoformat(as_of[:10])
    monday = today - timedelta(days=today.weekday())
    month = today.replace(day=1)
    previous_month = (month - timedelta(days=1)).replace(day=1)
    older_month = (previous_month - timedelta(days=1)).replace(day=1)
    return [('周', monday-timedelta(days=7), monday-timedelta(days=1),
             monday-timedelta(days=14), monday-timedelta(days=8)),
            ('月', previous_month, month-timedelta(days=1), older_month,
             previous_month-timedelta(days=1))]


def write_periods(sheet, rows, report):
    """Compare only fully covered natural periods, never silently widen the query."""
    first, last = (date.fromisoformat(report['query'][k]) for k in ('from', 'to'))
    for title, start, end, old_start, old_end in period_windows(report['as_of']):
        sheet.band(f'{title}度环比｜最近两个完整自然{title}')
        sheet.note(f'本期 {start} 至 {end}；上期 {old_start} 至 {old_end}。按签发业务日期分组；实收不做成熟度不同的环比。')
        sheet.row(['业务指标', '本期', '上期', '环比', '统计口径 / 阅读提示'], 'header')
        covered = first <= old_start and last >= end
        for scope in SCOPES:
            selected = rows if scope == '大盘' else [r for r in rows if r['warehouse'] == scope]
            current = [r for r in selected if str(start) <= r['day'] <= str(end)]
            previous = [r for r in selected if str(old_start) <= r['day'] <= str(old_end)]
            ms = [service.aggregate(x) for x in (current, previous)]
            for stage in service.STAGES[:-1]:
                x, y = [known_value(m, stage) if covered else None for m in ms]
                ratio = x/y-1 if x is not None and y is not None and y > 0 else None
                # Ratio cells have their own format; amounts remain currency.
                sheet.row([scope+' · '+service.NAMES[stage]+'货值（元）', x, y,
                           ratio,
                           '查询日期未覆盖两个完整周期，未计算' if not covered else
                           '已计价货值；缺资料留空，上期为0不计算环比'], fmt=MONEY, height=36, formats={3:PERCENT})


def write_dashboard(book, name, rows, report, group, progress, cancel):
    sheet = Sheet(book, name, [43, 21, 21, 21, 64], cancel)
    sheet.row(['门店补货订单漏斗｜'+group], 'title', height=38, merge=True)
    sheet.note(f"业务日期 {report['query']['from']} 至 {report['query']['to']}｜数据截至 {report['as_of'][:19]}｜当前导出范围")
    sheet.note('模型建议 → 签发 → 门店确认 → 实际下单 → 实际收货。数量按库存单位分列；五段货值按签发价；空白表示无有效资料。')
    sheet.row(['业务指标', *SCOPES, '统计口径 / 阅读提示'], 'header', height=32)
    scope_rows = [rows, *[[r for r in rows if r['warehouse'] == w] for w in SCOPES[1:]]]
    metrics = [service.aggregate(x) for x in scope_rows]

    def metric(label, values, note, fmt=NUMBER):
        sheet.row([label, *values, note], fmt=fmt, height=34)

    sheet.band('01｜统计范围')
    metric('补货订单数（店 × 仓 × 轮次）', [len({r['order'] for r in rs}) for rs in scope_rows], '包含本筛选范围内的订单；两仓为两张单。')
    metric('纳入漏斗订单数', [m['included_orders'] for m in metrics], '至少有一个纳入商品的订单。')
    for key, label in [('included','纳入商品条目'),('excluded','已排除商品条目'),('pending','资料待核商品条目')]:
        metric(label, [m[key] for m in metrics], '条目按订单+商品计数；同一商品跨订单重复出现。排除与待核不计入五段。')
    sheet.band('02｜数量漏斗（按库存单位分别合计）')
    us = units(rows)
    for unit in us:
        for stage in service.STAGES:
            metric(service.NAMES[stage]+'数量（'+unit+'）', [quantity(rs, stage, unit) for rs in scope_rows], '仅汇总本环节有效数量；不能直接用不同覆盖范围相减。')
        for a, b in service.PAIRS:
            metric(service.NAMES[b]+'/'+service.NAMES[a]+'（'+unit+'）',
                   [quantity_ratio(rs, a, b, unit) for rs in scope_rows],
                   '同一单位、同一有效商品集合；分母0留空，允许超过100%。', PERCENT)
    if not us:
        sheet.note('没有可汇总的已知库存单位；可在商品明细核对原数量，不猜测单位。')
    metric('库存单位未留存的纳入条目', [sum(r['scope']=='纳入' and r.get('unit') in (None,'') for r in rs) for rs in scope_rows], '数量不合并；若有签发价，仍按既有口径统计货值。')
    sheet.band('03｜货值漏斗（统一签发价，元）')
    for stage in service.STAGES:
        metric(service.NAMES[stage]+'已计价货值（元）', [known_value(m, stage) for m in metrics], '缺价条目不填0；实际付款金额另见“原单实际付款”。', MONEY)
        metric(service.NAMES[stage]+'缺价条目', [m['stages'][stage]['unpriced'] for m in metrics], '本环节数量有效，但无签发价；上述货值不含这些条目。')
    for index, (a,b) in enumerate(service.PAIRS):
        metric(service.NAMES[b]+'/'+service.NAMES[a]+'货值保留率', [m['pairs'][index]['ratio'] for m in metrics], '仅两环节均有效且已计价的同一商品集合，非上方总货值直接相除。', PERCENT)
    sheet.band('04｜收货覆盖与同样本实收')
    coverage = [receipt_coverage(rs) for rs in scope_rows]
    metric('已有完整实收记录的订单数', [c[0] for c in coverage], '该单纳入商品均有有效实收数量；已确认0属于有效记录。')
    metric('实收资料覆盖率', [c[1] for c in coverage], '已有完整实收记录订单数 / 纳入漏斗订单数。', PERCENT)
    for stage, label in [('payment','已记录实收样本的下单货值（元）'),('receipt','已记录实收样本的实收货值（元）')]:
        metric(label, [m['pairs'][-1]['before' if stage=='payment' else 'after'] for m in metrics], '付款和实收均有效且有签发价的同一商品集合。', MONEY)
    metric('已记录样本实收率', [m['pairs'][-1]['ratio'] for m in metrics], '同样本实收货值 / 下单货值；不把未收货当实收0。', PERCENT)
    sheet.note('未根据缺口推算GMV损失，未猜测到货延迟或未找到收货单。排除、必采属性均沿用当时冻结依据；缺依据单列待核。')
    write_periods(sheet, rows, report)
    progress('已生成：'+name)
    return name


RECORD_ID = ['仓属','门店名称','门店编码','轮次日期','补货单号','必采分组']


def write_records(book, rows, report, kind, progress, cancel):
    is_qty = kind == 'quantity'
    name = '门店数量记录' if is_qty else '门店货值记录'
    headers = RECORD_ID + (['库存单位'] if is_qty else [])
    headers += [service.NAMES[s]+('数量' if is_qty else '\n已计价货值（元）') for s in service.STAGES]
    headers += [service.NAMES[b]+'/'+service.NAMES[a] for a,b in service.PAIRS]
    headers += ['实收资料状态','数据截至','范围提示']
    widths = [14,34,25,14,44,16] + ([14] if is_qty else []) + [22]*9 + [24,23,50]
    sheet = Sheet(book, name, widths, cancel)
    sheet.row(['门店补货漏斗｜'+('数量记录' if is_qty else '货值记录')], 'title', height=38, merge=True)
    sheet.note('系统自动生成，无需手填；同店两仓分开。全部与必采分组是不同观察口径，不重复相加。')
    sheet.note('数量按库存单位分列；货值按签发价；空白不等于0；比率仅用同一有效商品集合。')
    sheet.row(headers, 'header', height=48)
    ordered = OrderedDict()
    for r in rows:
        ordered.setdefault(r['order'], []).append(r)
    for index, rs in enumerate(ordered.values(),1):
        for group in ('全部',*service.GROUPS):
            selected = rs if group == '全部' else [r for r in rs if r['group'] == group]
            if not selected:
                continue
            for unit in units(selected) if is_qty else [None]:
                relevant = [r for r in selected if str(r.get('unit')) == unit] if is_qty else selected
                metrics = service.aggregate(relevant)
                included = [r for r in relevant if r['scope']=='纳入']
                receipt = '已记录' if included and all(r['valid']['receipt'] for r in included) else '部分有效或待核' if any(r['valid']['receipt'] for r in included) else '无有效实收记录'
                first = rs[0]
                values = [first['warehouse'],first['store_name'],first['store'],first['day'],first['order'],group]
                if is_qty: values.append(unit)
                values += [quantity(relevant,s,unit) if is_qty else known_value(metrics,s) for s in service.STAGES]
                values += [quantity_ratio(relevant,a,b,unit) if is_qty else metrics['pairs'][i]['ratio'] for i,(a,b) in enumerate(service.PAIRS)]
                values += [receipt,report['as_of'][:19],f"纳入{metrics['included']}条；排除{metrics['excluded']}条；待核{metrics['pending']}条" + ('' if is_qty else '；各段缺价条目见汇总')]
                # Explicit per-column formats, without formulas or workbook re-reading.
                offset = len(RECORD_ID) + int(is_qty) + len(service.STAGES)
                sheet.row(values, fmt=NUMBER if is_qty else MONEY, height=36,
                          formats={offset+i:PERCENT for i in range(len(service.PAIRS))})
        if index % 100 == 0:progress(f'{name}：已写{index}/{len(ordered)}单')
    sheet.ws.auto_filter.ref=f'A4:{get_column_letter(len(headers))}{sheet.count}'
    progress('已生成：'+name)
    return name


def write_monitor(book, rows, report, progress=lambda _:None, cancel=None):
    names = []
    for group, name in [('全部','漏斗汇总'),('必采','必采漏斗'),('非必采','非必采漏斗'),('属性待核','属性待核漏斗')]:
        rs = rows if group=='全部' else [r for r in rows if r['group']==group]
        names.append(write_dashboard(book,name,rs,report,group,progress,cancel))
    names += [write_records(book,rows,report,kind,progress,cancel) for kind in ('quantity','value')]
    return names
